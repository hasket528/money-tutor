// ── 代碼與例句的取法（IEP 目標表單、教案包、教師指南共用，只定義在這裡）──────────────
// IEP_UNIT_CODES(k, stage)：stage 是 'sP'／'sA'／省略；該階沒有就退回 sP，common 一律附上。
window.IEP_UNIT_CODES = function (k, stage) {
  const r = (window.IEP_GOAL_UNIT_REF || {})[k];
  if (!r) return null;
  const use = stage && r[stage] ? stage : (r.sP ? 'sP' : null);
  const g = use ? r[use] : {}, c = r.common || {};
  return { stage: use, perf: [...(g.perf || []), ...(c.perf || [])], content: [...(g.content || []), ...(c.content || [])] };
};
// 範本層級對應的階段：獨立→sA，其餘→sP
window.IEP_LEVEL_STAGE = (level) => (level === '獨立' ? 'sA' : 'sP');
// IEP_UNIT_EXAMPLE(k)：教案包／教師指南的「IEP 目標例句」——main 是 sA 的單元取「獨立」，其餘取「進展」
window.IEP_UNIT_EXAMPLE = function (k) {
  const r = (window.IEP_GOAL_UNIT_REF || {})[k] || {}, level = r.main === 'sA' ? '獨立' : '進展';
  const t = ((window.IEP_GOAL_TEMPLATES || {})[k] || []).find(x => x.level === level);
  return t ? { level, iep: t.iep } : null;
};
